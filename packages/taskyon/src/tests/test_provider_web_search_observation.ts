import { getProviderWebSearchObservation } from '../tools/chatCompletion/streamResult'

function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(message)
}

export const testProviderWebSearchObservationReadsServerToolUsage = () => {
  for (const usageKey of ['server_tool_use', 'server_tool_use_details'] as const) {
    const observation = getProviderWebSearchObservation({
      usage: { [usageKey]: { web_search_requests: 2 } },
    })
    assert(observation?.performed === true, `Expected ${usageKey} to report completed search`)
    assert(observation.requests === 2, `Expected ${usageKey} request count`)
    assert(
      getProviderWebSearchObservation({ usage: { [usageKey]: { web_search_requests: 0 } } }) ===
        undefined,
      `Zero ${usageKey} requests must not count as search`,
    )
  }
  return { success: true }
}
testProviderWebSearchObservationReadsServerToolUsage.description =
  'Recognizes documented and observed hosted-search usage counters.'

export const testProviderWebSearchObservationReadsNestedSearchUsage = () => {
  const observation = getProviderWebSearchObservation({
    usage: { web_search: { num_requests: 2 } },
  })
  assert(observation?.performed === true, 'Expected nested web-search usage to count')
  assert(observation.requests === 2, 'Expected nested search request count')
  return { success: true }
}
testProviderWebSearchObservationReadsNestedSearchUsage.description =
  'Preserves the nested web-search usage format accepted before structured observation.'

export const testProviderWebSearchObservationRequiresCompletedEvent = () => {
  assert(
    getProviderWebSearchObservation({ type: 'response.web_search_call.completed' })?.performed ===
      true,
    'Expected a completed provider web-search event',
  )
  const completed = getProviderWebSearchObservation({
    type: 'response.output_item.done',
    item: { type: 'web_search_call', status: 'completed' },
  })
  assert(completed?.performed === true, 'Expected a completed provider web-search event')
  assert(
    getProviderWebSearchObservation({
      type: 'response.output_item.added',
      item: { type: 'web_search_call', status: 'in_progress' },
    }) === undefined,
    'A started search must not count as completed',
  )
  return { success: true }
}
testProviderWebSearchObservationRequiresCompletedEvent.description =
  'Counts completed provider search events without accepting started events.'

export const testProviderWebSearchObservationIgnoresAssistantText = () => {
  const observation = getProviderWebSearchObservation({
    choices: [
      {
        delta: {
          content:
            'response.web_search_call.completed\nserver_tool_use_details:\n  web_search_requests: 9',
        },
      },
    ],
  })
  assert(observation === undefined, 'Assistant text must not masquerade as hosted-search usage')
  return { success: true }
}
testProviderWebSearchObservationIgnoresAssistantText.description =
  'Rejects search-looking strings generated by the assistant.'
